"""Score Stage 2 (long V1 runs) as registered in the README.

usage (repo root): uv run --frozen experiments/2026-10-26-wall-vs-memory/scripts/analyse_stage2.py
Reads results/stage2_probe.csv; writes results/stage2_runs.csv and results/stage2_analysis.txt.
"""
from pathlib import Path

import numpy as np
import polars as pl

EXP = Path(__file__).resolve().parents[1]
LO, HI = 24, 30
SLOPE_LO, SLOPE_HI = 22, 31

df = pl.read_csv(EXP / "results/stage2_probe.csv")
rows = []
for spec in df["rule"].unique(maintain_order=True):
    g = df.filter(pl.col("rule") == spec).sort("k")
    row = dict(spec=spec, walker="rotor" if spec.startswith("rotor:") else "V1",
               escaped=bool(g["escaped"].any()), last_k=int(g["k"].max()))
    w = g.filter((pl.col("k") >= LO) & (pl.col("k") <= HI))
    if w.height == HI - LO + 1:
        t, A, P = (w[c].to_numpy().astype(float) for c in ("t", "area", "perimeter"))
        row["a"] = np.polyfit(np.log(t), np.log(A), 1)[0]
        row["beta"] = np.polyfit(np.log(A), np.log(P), 1)[0]
    s = g.filter((pl.col("k") >= SLOPE_LO - 1) & (pl.col("k") <= SLOPE_HI))
    if s.height == SLOPE_HI - SLOPE_LO + 2:
        k = s["k"].to_numpy()
        loc = np.diff(np.log2(s["area"].to_numpy().astype(float)))
        row["local_slope"] = np.polyfit(k[1:], loc, 1)[0]
        for kk, v in zip(k[1:], loc):
            row[f"loc{kk}"] = v
    rows.append(row)
runs = pl.DataFrame(rows)
runs.write_csv(EXP / "results/stage2_runs.csv", float_precision=6)

L = ["# wall-vs-memory Stage 2 (generated by scripts/analyse_stage2.py; do not edit)"]
p = L.append
rng = np.random.default_rng(20261026)
for name in ("rotor", "V1"):
    g = runs.filter(pl.col("walker") == name)
    a = g["a"].drop_nulls().to_numpy()
    b = g["beta"].drop_nulls().to_numpy()
    sl = g["local_slope"].drop_nulls().to_numpy()
    boot = np.array([rng.choice(sl, len(sl)).mean() for _ in range(10_000)]) if len(sl) else np.array([np.nan])
    lo, hi = np.percentile(boot, [2.5, 97.5])
    locs = {kk: g[f"loc{kk}"].drop_nulls().mean() for kk in range(SLOPE_LO, SLOPE_HI + 1) if f"loc{kk}" in g.columns}
    p(f"{name}: runs {g.height}, escaped {int(g['escaped'].sum())}, fitted {len(a)}; a({LO}..{HI}) {a.mean():.3f} "
      f"(sd {a.std(ddof=1):.3f}); beta {b.mean():.3f} (sd {b.std(ddof=1):.3f}); local-a slope per octave "
      f"{sl.mean():+.4f} (n {len(sl)}, bootstrap 95% [{lo:+.4f}, {hi:+.4f}])")
    p("  mean local a by octave: " + " ".join(f"{kk}:{v:.3f}" for kk, v in locs.items()))
    if name == "rotor":
        s0 = 0.65 <= a.mean() <= 0.70
        p(f"S0 rotor a in [0.65, 0.70]: {'PASS' if s0 else 'FAIL'}")
    else:
        if a.mean() <= 0.72 and hi < 0:
            reading = "converging (wall suffices in the long run)"
        elif a.mean() >= 0.73 and lo <= 0 <= hi:
            reading = "separate exponent (memory needed for the rest)"
        else:
            reading = "unresolved at this horizon"
        p(f"V1 reading: {reading}{'' if s0 else ' [NOT SCORED: S0 failed]'}")
(EXP / "results/stage2_analysis.txt").write_text("\n".join(L) + "\n")
print("\n".join(L))
