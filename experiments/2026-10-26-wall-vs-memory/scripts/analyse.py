"""Score the wall-vs-memory factorial exactly as registered in the README.

usage (repo root): uv run --frozen experiments/2026-10-26-wall-vs-memory/scripts/analyse.py
Reads results/probe.csv and the census summary; writes results/runs.csv, results/conditions.csv
and results/analysis.txt. Per-run fits as experiments/2026-10-19-kappa-walker-reference/scripts/analyse.py:
a = slope ln area vs ln t, beta = slope ln perimeter vs ln area, kappa = mean over windows of
(boundary_steps / (t/2)) / (perimeter/area), g_k = slope ln kappa vs ln t; t is the window end.
"""
from pathlib import Path

import numpy as np
import polars as pl

ROOT = Path(__file__).resolve().parents[3]
EXP = Path(__file__).resolve().parents[1]
WINDOWS = {"early": (12, 22), "late": (20, 26)}


def fit(g: pl.DataFrame, lo: int, hi: int) -> dict | None:
    w = g.filter((pl.col("k") >= lo) & (pl.col("k") <= hi))
    if w.height < hi - lo + 1:
        return None
    t = w["t"].to_numpy().astype(float)
    A = w["area"].to_numpy().astype(float)
    P = w["perimeter"].to_numpy().astype(float)
    kap = (w["boundary_steps"].to_numpy() / (t / 2)) / (P / A)
    return dict(
        a=np.polyfit(np.log(t), np.log(A), 1)[0],
        beta=np.polyfit(np.log(A), np.log(P), 1)[0],
        kappa=kap.mean(),
        g_k=np.polyfit(np.log(t), np.log(kap), 1)[0],
    )


def condition(spec: str) -> tuple[str, str, float, float]:
    """(group, rule, ev, ef). Rule-free corners are grouped across rules."""
    if spec.startswith("rotor:"):
        return ("rotor", "-", np.nan, np.nan)
    _, rule, ev, ef, _ = spec.split(":")
    ev, ef = float(ev), float(ef)
    if ev == 1.0:
        return (f"hy:*:{ev:g}:{ef:g}", "*", ev, ef)
    return (f"hy:{rule}:{ev:g}:{ef:g}", rule, ev, ef)


def classify(c: dict) -> str:
    a, b = c.get("early_a"), c.get("early_beta")
    if a is None or np.isnan(a):
        return "no early fit"
    if a <= 0.78 and b <= 0.65:
        if c["late_n"] >= 6 and not c["late_a"] <= 0.74:
            return "intermediate"
        return "compact"
    if a >= 0.85 and b >= 0.80:
        return "porous"
    return "intermediate"


df = pl.read_csv(EXP / "results/probe.csv")
runs = []
for spec in df["rule"].unique(maintain_order=True):
    g = df.filter(pl.col("rule") == spec).sort("k")
    grp, rule, ev, ef = condition(spec)
    row = dict(spec=spec, group=grp, rule=rule, ev=ev, ef=ef, escaped=bool(g["escaped"].any()),
               last_k=int(g["k"].max()))
    for name, (lo, hi) in WINDOWS.items():
        f = fit(g, lo, hi)
        for key in ("a", "beta", "kappa", "g_k"):
            row[f"{name}_{key}"] = f[key] if f else None
    runs.append(row)
runs = pl.DataFrame(runs)
runs.write_csv(EXP / "results/runs.csv", float_precision=6)

conds = []
for grp in runs["group"].unique(maintain_order=True):
    g = runs.filter(pl.col("group") == grp)
    c = dict(group=grp, rule=g["rule"][0], ev=g["ev"][0], ef=g["ef"][0], runs=g.height,
             escaped=int(g["escaped"].sum()))
    for name in WINDOWS:
        ok = g.filter(pl.col(f"{name}_a").is_not_null())
        c[f"{name}_n"] = ok.height
        for key in ("a", "beta", "kappa", "g_k"):
            x = ok[f"{name}_{key}"].to_numpy().astype(float)
            c[f"{name}_{key}"] = float(x.mean()) if len(x) else np.nan
            c[f"{name}_{key}_sd"] = float(x.std(ddof=1)) if len(x) > 1 else np.nan
    c["class"] = classify(c)
    conds.append(c)
conds = pl.DataFrame(conds)
conds.write_csv(EXP / "results/conditions.csv", float_precision=6)
C = {r["group"]: r for r in conds.iter_rows(named=True)}

L = []
p = L.append
f3 = lambda x: "nan" if x is None or np.isnan(x) else f"{x:.3f}"
p("# wall-vs-memory analysis (generated by scripts/analyse.py; do not edit)")
p(f"runs {runs.height}, conditions {conds.height}, runs with an escape {int(runs['escaped'].sum())}")
p("")
p("## Conditions (mean over runs; sd in brackets; early k=12..22, late k=20..26)")
p("group | runs | esc | early n | early a | early beta | early kappa | early g_k | late n | late a | late beta | late kappa | late g_k | class")
for c in conds.iter_rows(named=True):
    p(" | ".join([c["group"], str(c["runs"]), str(c["escaped"]), str(c["early_n"]),
                  f"{f3(c['early_a'])} ({f3(c['early_a_sd'])})", f"{f3(c['early_beta'])} ({f3(c['early_beta_sd'])})",
                  f3(c["early_kappa"]), f3(c["early_g_k"]), str(c["late_n"]),
                  f"{f3(c['late_a'])} ({f3(c['late_a_sd'])})", f"{f3(c['late_beta'])} ({f3(c['late_beta_sd'])})",
                  f3(c["late_kappa"]), f3(c["late_g_k"]), c["class"]]))
p("")

# Gates
rot = C["rotor"]
g1 = (0.68 <= rot["early_a"] <= 0.77) and (0.53 <= rot["early_beta"] <= 0.62) and (0.66 <= rot["late_a"] <= 0.71)
p(f"G1 rotor: early a {f3(rot['early_a'])} in [0.68,0.77], beta {f3(rot['early_beta'])} in [0.53,0.62], "
  f"late a {f3(rot['late_a'])} in [0.66,0.71]: {'PASS' if g1 else 'FAIL'}")
pw = C["hy:*:1:1"]
g2 = abs(pw["early_a"] - 0.92) <= 0.03 and abs(pw["early_beta"] - 0.91) <= 0.04
p(f"G2 hy:*:1:1 (= pw:0.5): early a {f3(pw['early_a'])} (0.92 +- 0.03), beta {f3(pw['early_beta'])} (0.91 +- 0.04): "
  f"{'PASS' if g2 else 'FAIL'}")
census = pl.read_csv(ROOT / "experiments/2026-10-13-probe-growth-census/results/probe_summary.csv")
rules = (EXP / "results/rules.txt").read_text().split()
g3 = True
for r in rules:
    det = C[f"hy:{r}:0:0"]
    cen = census.filter(pl.col("rule") == r).row(0, named=True)
    da, db = det["late_a"] - cen["a"], det["late_beta"] - cen["beta"]
    ok = abs(da) <= 0.005 and abs(db) <= 0.005 and det["class"] == "compact"
    g3 &= ok
    p(f"G3 {r}: late a {f3(det['late_a'])} vs census {f3(cen['a'])} (d {da:+.4f}), beta d {db:+.4f}, "
      f"class {det['class']}: {'ok' if ok else 'FAIL'}")
p(f"G3: {'PASS' if g3 else 'FAIL'}")
gates = g1 and g2 and g3
p(f"gates: {'all pass, factorial scored' if gates else 'a gate failed: factorial reported, NOT scored'}")
p("")

# Corners
v1 = C["hy:*:1:0"]
p(f"V1 (hybrid wall walker, hy:*:1:0): class {v1['class']} (early a {f3(v1['early_a'])}, beta {f3(v1['early_beta'])}, "
  f"late n {v1['late_n']}, late a {f3(v1['late_a'])}). H-wall predicts compact, H-memory porous.")
mem_n = wall_n = 0
deltas = []
for r in rules:
    a0 = C[f"hy:{r}:0:0"]["early_a"]
    f1 = C[f"hy:{r}:0:1"]
    d = f1["early_a"] - a0
    mem_ok = f1["class"] == "compact" and abs(d) <= 0.03
    wall_ok = f1["class"] == "porous" or d >= 0.05
    mem_n += mem_ok
    wall_n += wall_ok
    dv = C[f"hy:{r}:0.1:0"]["early_a"] - a0
    df_ = C[f"hy:{r}:0:0.1"]["early_a"] - a0
    d01 = C[f"hy:{r}:0.01:0"]["early_a"] - a0
    deltas.append((r, dv, df_, d01))
    p(f"F1 {r}: class {f1['class']}, early a {f3(f1['early_a'])} vs deterministic {f3(a0)} (d {d:+.3f}); "
      f"H-memory criterion {'met' if mem_ok else 'not met'}, H-wall criterion {'met' if wall_ok else 'not met'}")
f1_read = "compact (H-memory side)" if mem_n >= 5 else ("wall-side (porous or raised)" if wall_n >= 5 else "split across rules")
p(f"F1 summary: H-memory criterion in {mem_n}/6 rules, H-wall criterion in {wall_n}/6 rules -> {f1_read}")
v1c = v1["class"]
if v1c == "porous" and mem_n >= 5:
    reading = "H-memory supported (wall neither needed nor sufficient)"
elif v1c == "compact" and wall_n >= 5:
    reading = "H-wall supported"
elif v1c == "compact" and mem_n >= 5:
    reading = "both compact: either ingredient suffices"
elif v1c == "porous" and wall_n >= 5:
    reading = "both fail: neither suffices alone"
else:
    reading = "no registered reading applies (intermediate class or rule-split F1)"
p(f"corner reading: {reading}{'' if gates else ' [NOT SCORED: gate failed]'}")
p("")

# Dose arms
p("rule | Delta_V (0.1,0) | Delta_F (0,0.1) | Delta_V - Delta_F | Delta (0.01,0)")
mem_dose = wall_dose = small_ok = 0
for r, dv, df_, d01 in deltas:
    mem_dose += (dv - df_) >= 0.03
    wall_dose += (df_ - dv) >= 0.03
    small_ok += abs(d01) <= 0.02
    p(f"{r} | {dv:+.3f} | {df_:+.3f} | {dv - df_:+.3f} | {d01:+.3f}")
p(f"dose: Delta_V - Delta_F >= 0.03 in {mem_dose}/6 (H-memory needs >= 5); Delta_F - Delta_V >= 0.03 in "
  f"{wall_dose}/6 (H-wall needs >= 5); |Delta(0.01,0)| <= 0.02 in {small_ok}/6 (expected)")
both = [C[f"hy:{r}:0.1:0.1"]["early_a"] for r in rules]
p(f"(0.1,0.1) early a per rule {[round(x, 3) for x in both]}, median {np.median(both):.3f} "
  f"(D3 at eps 0.1: median 0.761; different rules, stream and window, so descriptive)")

(EXP / "results/analysis.txt").write_text("\n".join(L) + "\n")
print("\n".join(L))
