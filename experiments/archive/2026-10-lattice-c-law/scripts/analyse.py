"""Lattice c law: fit 1/c = a + b*lead per (lattice, stratum), decide H-A/H-B/H-C, kappa ratios (README, 'Predictions').
usage: uv run experiments/archive/2026-10-lattice-c-law/scripts/analyse.py
Reads results/{ants,controls}.csv and results/lists/ants.txt; writes results/analysis.{txt,json}. Deterministic (seed 20261020)."""
import json
from pathlib import Path

import numpy as np
import polars as pl

R = Path(__file__).resolve().parents[1] / "results"
SEED, NB = 20261020, 2000
LO, HI = 20, 26          # ants and mean-field windows
RW_LO, RW_HI = 16, 22    # random walk escapes the 8192 board before 2^27: its own window range (documented deviation)
lines = []


def say(s=""):
    print(s)
    lines.append(s)


def slope(x, y):
    return float(np.polyfit(np.log(x), np.log(y), 1)[0])


def kappa_unif(a, beta):
    p = a * (1 - beta)
    return 2 * (1 - 2 ** -(1 - p)) / (1 - p)


def per_run(df, lo, hi, need_unescaped):
    out = []
    for (lat, spec), g in df.group_by(["lattice", "spec"], maintain_order=True):
        if need_unescaped and g["escaped"][0]:
            continue
        g = g.filter((pl.col("k") >= lo) & (pl.col("k") <= hi)).sort("k")
        if g.height < hi - lo + 1 or (g["new_cells"] == 0).any() or (g["boundary_steps"] == 0).any():
            continue
        t = (2.0 ** (g["k"].to_numpy() + 1))
        area, per = g["area"].to_numpy().astype(float), g["perimeter"].to_numpy().astype(float)
        B = g["boundary_steps"].to_numpy() / (t / 2)
        kap = B / (per / area)
        wmax = np.maximum(g["width"].to_numpy(), g["height"].to_numpy()).astype(float)
        a, beta = slope(t, area), slope(area, per)
        out.append(dict(lattice=lat, spec=spec, a=a, beta=beta, alpha_w=slope(t, wmax), g_k=slope(t, kap),
                        c=float(g["new_cells"][-1] / g["boundary_steps"][-1]), kappa=float(kap[-1]),
                        kratio=float(kap[-1] / kappa_unif(a, beta))))
    return pl.DataFrame(out)


def lead_of(rule):
    k = 1
    while k < len(rule) and rule[k] == rule[0]:
        k += 1
    return k


ants = pl.read_csv(R / "ants.csv")
ctl = pl.read_csv(R / "controls.csv")
pairs = [ln.split(" ", 1) for ln in (R / "lists" / "ants.txt").read_text().splitlines() if ln.strip()]
runs = pl.DataFrame({"lattice": [p[0] for p in pairs], "spec": [p[1] for p in pairs]})
per = per_run(ants, LO, HI, True)
cand = runs.with_columns(rule=pl.col("spec").str.slice(4), stratum=pl.col("spec").str.slice(4, 1)).with_columns(
    lead=pl.col("rule").map_elements(lead_of, return_dtype=pl.Int64))
joined = cand.join(per, on=["lattice", "spec"], how="left")
joined = joined.with_columns(
    kept=(pl.col("c").is_not_null() & (pl.col("c") > 0) & (pl.col("g_k").abs() < 0.05) & pl.col("alpha_w").is_between(0.28, 0.40)),
    ran=pl.col("c").is_not_null())

say("# Lattice c law: analysis (generated by scripts/analyse.py; seed 20261020)")
say()
say("## Retention (kept = survived to 2^27, all windows 20..26, c>0, |g_k|<0.05, alpha_w in [0.28,0.40]) / candidates 48")
say(f"{'lattice':7} {'stratum':7} " + " ".join(f"lead{m}" for m in range(1, 6)) + "   alive(not escaped, windows ok)")
ret = {}
for (lat, s0), g in joined.group_by(["lattice", "stratum"], maintain_order=True):
    row = [int(g.filter(pl.col("lead") == m)["kept"].sum()) for m in range(1, 6)]
    alive = [int(g.filter(pl.col("lead") == m)["ran"].sum()) for m in range(1, 6)]
    ret[f"{lat}/{s0}"] = dict(kept=row, alive=alive)
    say(f"{lat:7} {s0:7} " + " ".join(f"{r:5d}" for r in row) + "   " + " ".join(str(a) for a in alive))
under = [k for k, v in ret.items() if any(x < 8 for x in v["kept"])]
say("underpowered cells (<8 kept) in strata: " + (", ".join(under) if under else "none"))

kept = joined.filter(pl.col("kept"))
rng = np.random.default_rng(SEED)
fits = {}


def fit(L, y):
    X = np.column_stack([np.ones(len(L)), L])
    return np.linalg.lstsq(X, y, rcond=None)[0]


say()
say("## 1/c = a + b*lead per (lattice, stratum): leads 1..5, kept rules, 2000-draw rule bootstrap (95% percentile CI)")
boot_b = {}
for (lat, s0), g in kept.group_by(["lattice", "stratum"], maintain_order=True):
    L, y = g["lead"].to_numpy().astype(float), 1.0 / g["c"].to_numpy()
    a_, b_ = fit(L, y)
    bs = np.empty((NB, 2))
    for i in range(NB):
        ix = rng.integers(0, len(L), len(L))
        bs[i] = fit(L[ix], y[ix]) if len(set(L[ix])) > 1 else (np.nan, np.nan)
    pred = a_ + b_ * L
    r2 = 1 - ((y - pred) ** 2).sum() / ((y - y.mean()) ** 2).sum()
    key = f"{lat}/{s0}"
    fits[key] = dict(n=len(L), a=a_, b=b_, r2=r2, a_ci=list(np.nanpercentile(bs[:, 0], [2.5, 97.5])), b_ci=list(np.nanpercentile(bs[:, 1], [2.5, 97.5])))
    boot_b[key] = bs[:, 1]
    say(f"{key:10} n={len(L):3d}  a={a_:.3f} [{fits[key]['a_ci'][0]:.3f},{fits[key]['a_ci'][1]:.3f}]  b={b_:.3f} [{fits[key]['b_ci'][0]:.3f},{fits[key]['b_ci'][1]:.3f}]  R2={r2:.3f}")

say()
say("## Gate G5 (square): median slope in [0.55,0.85], intercept in [1.20,1.60]")
sq = fits.get("square/R")
if sq:
    say(f"square b={sq['b']:.3f} a={sq['a']:.3f}  ->  {'PASS' if 0.55 <= sq['b'] <= 0.85 and 1.20 <= sq['a'] <= 1.60 else 'FAIL'}")

say()
say("## Hypothesis vectors (triangular, hex R-lead, hex r-lead)")
H = {"A": (1.05, 0.52, 1.05), "B": (0.70, 0.70, 0.70), "C": (0.93, 0.47, 0.47)}
verdict = None
if all(k in fits for k in ["tri/R", "hex/R", "hex/r"]):
    meas = np.array([fits["tri/R"]["b"], fits["hex/R"]["b"], fits["hex/r"]["b"]])
    say(f"measured b = ({meas[0]:.3f}, {meas[1]:.3f}, {meas[2]:.3f})")
    dev = {h: np.abs(meas - np.array(v)) for h, v in H.items()}
    for h, d in dev.items():
        say(f"  H-{h}: max |dev| {d.max():.3f}  (devs {', '.join(f'{x:.3f}' for x in d)})")
    sup = [h for h, d in dev.items() if d.max() <= 0.15 and all(dev[o].max() > 0.20 for o in H if o != h)]
    verdict = sup[0] if sup else "undecided"
    say(f"decision rule (all within 0.15 and every rival off by >0.20 somewhere): {verdict}")
    ratio = boot_b["hex/r"] / boot_b["hex/R"]
    lo_, hi_ = np.nanpercentile(ratio, [2.5, 97.5])
    say(f"L1 b_r/b_R = {fits['hex/r']['b'] / fits['hex/R']['b']:.3f} [{lo_:.3f},{hi_:.3f}]  excludes 1: {not (lo_ <= 1 <= hi_)}")
    for lat in ["square", "tri", "hex"]:
        for k, f in fits.items():
            if k.startswith(lat + "/"):
                ok = f["a"] > 0 and abs(f["a"] - 1.36) < 0.5
                say(f"L2 {k}: a={f['a']:.3f} within 0.5 of 1.36: {ok}")
else:
    say("missing a stratum fit; no decision")

say()
say("## Kappa: ratio kappa/kappa_unif(a, beta) per run, own (a, beta), k=20..26 (ants, mean-field), 16..22 (random walk)")
cper = pl.concat([
    per_run(ctl.filter(pl.col("spec").str.starts_with("mf")), LO, HI, True).with_columns(kind=pl.lit("mf")),
    per_run(ctl.filter(pl.col("spec").str.starts_with("rw")), RW_LO, RW_HI, False).with_columns(kind=pl.lit("rw")),
]) if ctl.height else pl.DataFrame()
kap = {}
for lat in ["square", "tri", "hex"]:
    ka = kept.filter(pl.col("lattice") == lat)["kratio"].to_numpy()
    row = {"ants_n": len(ka), "ants_median": float(np.median(ka)) if len(ka) else None,
           "ants_q": [float(x) for x in np.percentile(ka, [10, 25, 75, 90])] if len(ka) else None}
    for kind in ["mf", "rw"]:
        c_ = cper.filter((pl.col("lattice") == lat) & (pl.col("kind") == kind)) if cper.height else cper
        row[kind] = dict(n=c_.height, ratio_mean=float(c_["kratio"].mean()) if c_.height else None,
                         ratio_sd=float(c_["kratio"].std()) if c_.height > 1 else None,
                         c_mean=float(c_["c"].mean()) if c_.height else None,
                         a_mean=float(c_["a"].mean()) if c_.height else None, beta_mean=float(c_["beta"].mean()) if c_.height else None)
    row["ants_c_median"] = float(kept.filter(pl.col("lattice") == lat)["c"].median()) if len(ka) else None
    kap[lat] = row
    say(f"{lat:6} ants n={row['ants_n']} median ratio {row['ants_median']}  q10/25/75/90 {row['ants_q']}")
    for kind in ["mf", "rw"]:
        r = row[kind]
        say(f"       {kind}: n={r['n']} ratio {r['ratio_mean']} (sd {r['ratio_sd']})  c {r['c_mean']}  a {r['a_mean']} beta {r['beta_mean']}")
    say(f"       ant median c {row['ants_c_median']}")

say()
say("## K3: slope of ln kappa on lead per stratum (|slope| < 0.08 predicted)")
k3 = {}
for (lat, s0), g in kept.group_by(["lattice", "stratum"], maintain_order=True):
    if g.height > 3:
        s = fit(g["lead"].to_numpy().astype(float), np.log(g["kappa"].to_numpy()))[1]
        k3[f"{lat}/{s0}"] = float(s)
        say(f"{lat}/{s0}: {s:.3f}")

say()
say("## Predictions scorecard (kappa)")
for lat in ["tri", "hex"]:
    m = kap[lat]["ants_median"]
    if m is not None:
        say(f"K1 {lat}: median ratio {m:.3f} < 1: {m < 1}; in [0.65,0.97]: {0.65 <= m <= 0.97}")
for lat in ["square", "tri", "hex"]:
    rwr = kap[lat]["rw"]["ratio_mean"]
    mfr = kap[lat]["mf"]["ratio_mean"]
    if mfr is not None:
        say(f"G4 {lat}: mean-field ratio {mfr:.3f} within 0.05 of 1: {abs(mfr - 1) <= 0.05}")
    if rwr is not None:
        say(f"K2 {lat}: rw ratio {rwr:.3f} >= 1.10: {rwr >= 1.10}")
    if kap[lat]["rw"]["c_mean"] is not None and kap[lat]["ants_c_median"] is not None:
        say(f"K4 {lat}: rw c {kap[lat]['rw']['c_mean']:.3f} < ant median c {kap[lat]['ants_c_median']:.3f}: {kap[lat]['rw']['c_mean'] < kap[lat]['ants_c_median']}")

(R / "analysis.txt").write_text("\n".join(lines) + "\n")
(R / "analysis.json").write_text(json.dumps(dict(fits=fits, retention=ret, kappa=kap, k3=k3, verdict=verdict), indent=1, default=float))
