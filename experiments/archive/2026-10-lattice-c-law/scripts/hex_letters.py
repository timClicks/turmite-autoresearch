"""Follow-up A (README): hex letter-typed lead with a perimeter-exponent filter beta < 0.8. T1-T5 as registered.
usage: uv run experiments/archive/2026-10-lattice-c-law/scripts/hex_letters.py -> results/hex_letters.txt. Deterministic (seed 20261020)."""
import contextlib, io, runpy
from pathlib import Path
import numpy as np
import polars as pl

with contextlib.redirect_stdout(io.StringIO()):
    ns = runpy.run_path(str(Path(__file__).with_name("analyse.py")))
kept, R = ns["kept"], ns["R"]
SEED, NB = 20261020, 2000
lines = []


def say(s=""):
    print(s)
    lines.append(s)


def f_big(rule, lead):
    tail = rule[lead:]
    return sum(ch in "RL" for ch in tail) / len(tail)


def ols(X, y):
    return np.linalg.lstsq(X, y, rcond=None)[0]


def design(L, f, with_f):
    cols = [np.ones(len(L)), L] + ([f] if with_f else [])
    return np.column_stack(cols)


def r2(y, p):
    return 1 - ((y - p) ** 2).sum() / ((y - y.mean()) ** 2).sum()


def cv_r2(L, f, y, with_f):
    pred = np.empty(len(y))
    idx = np.arange(len(y))
    for k in range(5):
        te = idx % 5 == k
        w = ols(design(L[~te], f[~te], with_f), y[~te])
        pred[te] = design(L[te], f[te], with_f) @ w
    return r2(y, pred)


hx = kept.filter(pl.col("lattice") == "hex").with_columns(
    fb=pl.struct("rule", "lead").map_elements(lambda s: f_big(s["rule"], s["lead"]), return_dtype=pl.Float64))
rng = np.random.default_rng(SEED)
say("# Follow-up A: hex letter types (generated by scripts/hex_letters.py; seed 20261020)")
res = {}
for s0 in ["r", "R"]:
    g0 = hx.filter(pl.col("stratum") == s0)
    g = g0.filter(pl.col("beta") < 0.8)
    dropped = g0.filter(pl.col("beta") >= 0.8)
    say(f"\n## stratum {s0}-lead: kept {g0.height}, beta>=0.8 dropped {dropped.height} {list(dropped['spec'])}, remaining {g.height}")
    L, f, y = g["lead"].to_numpy().astype(float), g["fb"].to_numpy(), 1 / g["c"].to_numpy()
    out = {}
    for name, wf in [("M0", False), ("M1", True)]:
        w = ols(design(L, f, wf), y)
        bs = []
        for _ in range(NB):
            ix = rng.integers(0, len(L), len(L))
            if len(set(L[ix])) > 1:
                bs.append(ols(design(L[ix], f[ix], wf), y[ix]))
        bs = np.array(bs)
        ci = np.percentile(bs, [2.5, 97.5], axis=0)
        out[name] = dict(w=w, ci=ci, r2=r2(y, design(L, f, wf) @ w), cv=cv_r2(L, f, y, wf), boot=bs)
        names = ["a", "b"] + (["d"] if wf else [])
        say(f"{name}: " + "  ".join(f"{n}={w[i]:.3f} [{ci[0, i]:.3f},{ci[1, i]:.3f}]" for i, n in enumerate(names))
            + f"  R2={out[name]['r2']:.3f}  CV-R2={out[name]['cv']:.3f}")
    say(f"mean f_big {f.mean():.3f} sd {f.std():.3f}; corr(lead, f_big) {np.corrcoef(L, f)[0, 1]:.3f}")
    res[s0] = out
b_r, b_R = res["r"]["M0"]["w"][1], res["R"]["M0"]["w"][1]
n = min(len(res["r"]["M0"]["boot"]), len(res["R"]["M0"]["boot"]))
ratio = res["r"]["M0"]["boot"][:n, 1] / res["R"]["M0"]["boot"][:n, 1]
lo, hi = np.percentile(ratio, [2.5, 97.5])
say(f"\nb_r/b_R (M0, F2) = {b_r / b_R:.3f} [{lo:.3f},{hi:.3f}]")
say("\n## Scorecard")
say(f"T1 r-lead R2>=0.5 and b in [0.15,0.45]: R2 {res['r']['M0']['r2']:.3f}, b {b_r:.3f} -> {res['r']['M0']['r2'] >= 0.5 and 0.15 <= b_r <= 0.45}")
say(f"T2 R-lead b within 0.1 of 0.876: {b_R:.3f} -> {abs(b_R - 0.876) <= 0.1}")
dcv = res["R"]["M1"]["cv"] - res["R"]["M0"]["cv"]
dci = [(s, res[s]["M1"]["ci"][:, 2]) for s in "rR"]
say(f"T3 R-lead CV gain M1-M0 {dcv:.3f} (>=0.05: {dcv >= 0.05}); d CI excludes 0: " + ", ".join(f"{s}: {c[0]:.3f}..{c[1]:.3f} -> {not (c[0] <= 0 <= c[1])}" for s, c in dci))
say(f"T4 r-lead M1 intercept at f_big=0 {res['r']['M1']['w'][0]:.3f} < 2.0: {res['r']['M1']['w'][0] < 2.0}")
say(f"T5 b_r/b_R CI below 1: {hi < 1}")
(R / "hex_letters.txt").write_text("\n".join(lines) + "\n")
