"""Task C3: generate lean/Data.lean (finite certificates for the two shift lemmas, q = 0, 1, 2) from the second checker's data.
usage: python3 c3_gen.py > lean/Data.lean   (the rows are those c1b.py finds; Lean re-checks the runs by kernel evaluation)"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from c1_ant import parse_canonical
import c1b

ph = parse_canonical()
row = lambda r: "[" + ", ".join(map(str, r)) + "]"
out = []
w = out.append
w("import Model\nimport Iter\n")
w("/-! GENERATED by scripts/c3_gen.py from scripts/c1b.py (do not edit). Rows: columns x = -3 .. 47, colours 0..5.")
w("    For each phase q: the descent certificate (20 steps on [A, bulk, bulk]) and the return certificate (4 steps on")
w("    [r', r', A'] without the sentinel row), each by `decide +kernel`, then the iteration theorems for all n. -/")
w("namespace Sweeper\n")
for q in range(3):
    d = c1b.verify_phase("RLRLLL", ph, q, [], 100)["_data"]
    assert len(d["rp"]) == 2 and len(d["rpp"]) == 2 and len(d["A"]) == 1 and len(d["Ap"]) == 1
    A, Ap = d["A"][0], d["Ap"][0]
    X1, H1, X3, H3 = d["x1"], d["h1"], d["x3"], d["h3"]
    w(f"def bulk{q} : Row := {row(d['bulk'])}")
    w(f"def A{q} : Row := {row(A)}")
    w(f"def rp{q} : List Row := [{row(d['rp'][0])},\n  {row(d['rp'][1])}]")
    w(f"def Ap{q} : Row := {row(Ap)}")
    w(f"def rpp{q} : List Row := [{row(d['rpp'][0])},\n  {row(d['rpp'][1])}]\n")
    w(f"theorem descent_cert{q} : runN 20 {{ g := [A{q}, bulk{q}, bulk{q}], x := {X1}, y := 1, h := {H1} }}")
    w(f"    = some {{ g := rp{q} ++ [A{q}], x := {X1}, y := 3, h := {H1} }} := by decide +kernel\n")
    w(f"theorem return_cert{q} : runN 4 {{ g := rp{q} ++ [Ap{q}], x := {X3}, y := 1, h := {H3} }}")
    w(f"    = some {{ g := [Ap{q}] ++ rpp{q}, x := {X3}, y := -1, h := {H3} }} := by decide +kernel\n")
    w(f"theorem descent_all{q} : ∀ (n : Nat) (pre post : List Row),")
    w(f"    runN (20 * n) {{ g := pre ++ [A{q}] ++ List.replicate (2 * n) bulk{q} ++ post, x := {X1}, y := pre.length + 1, h := {H1} }}")
    w(f"      = some {{ g := pre ++ (List.replicate n rp{q}).flatten ++ [A{q}] ++ post, x := {X1}, y := pre.length + 1 + 2 * (n : Int), h := {H1} }} :=")
    w(f"  descent_iter A{q} bulk{q} rp{q} ({X1}) {H1} rfl descent_cert{q}\n")
    w(f"theorem return_all{q} : ∀ (n : Nat) (pre post : List Row),")
    w(f"    runN (4 * n) {{ g := pre ++ (List.replicate n rp{q}).flatten ++ [Ap{q}] ++ post, x := {X3}, y := pre.length + 2 * (n : Int) - 1, h := {H3} }}")
    w(f"      = some {{ g := pre ++ [Ap{q}] ++ (List.replicate n rpp{q}).flatten ++ post, x := {X3}, y := pre.length - 1, h := {H3} }} :=")
    w(f"  return_iter Ap{q} rp{q} rpp{q} ({X3}) {H3} rfl return_cert{q}\n")
w("end Sweeper")
print("\n".join(out))
