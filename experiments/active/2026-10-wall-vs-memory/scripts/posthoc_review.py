"""Post-hoc sensitivity checks added after review of PR 19 (NOT registered predictions).

usage (repo root): uv run --frozen experiments/active/2026-10-wall-vs-memory/scripts/posthoc_review.py [RESULTS_DIR]
Reads results/runs.csv, conditions.csv, stage2_probe.csv; writes results/posthoc_review.txt.
Everything here is descriptive; the registered scores in analysis.txt / stage2_analysis.txt stand.

 1. F1 individual runs against the porous thresholds (early a >= 0.85 and early beta >= 0.80),
    the same numbers the registered rule applies to condition MEANS.
 2. Mean early-a shift under 10% noise (revisit-only, fresh-only) relative to the noise-free ant.
 3. Stage 2 V1 and rotor: seed-level 95% interval of the mean a(24..30), and a(k) refit over
    CSV k = 27..31 (equal-width late window, 5 octaves, ending at 2^31), plus the
    seed-level spread of the difference between the two windows. k is log2 of the window END t.
"""
import sys
from pathlib import Path

import numpy as np
import polars as pl

EXP = Path(__file__).resolve().parents[1]
RES = Path(sys.argv[1]) if len(sys.argv) > 1 else EXP / "results"
L = ["# post-hoc review checks (generated by scripts/posthoc_review.py; descriptive, not registered)"]
p = L.append

runs = pl.read_csv(RES / "runs.csv")
rules = (EXP / "results/rules.txt").read_text().split()
f1 = runs.filter(pl.col("group").str.starts_with("hy:") & (pl.col("ev") == 0.0) & (pl.col("ef") == 1.0))
ok = f1.with_columns(((pl.col("early_a") >= 0.85) & (pl.col("early_beta") >= 0.80)).alias("porous_run"))
p(f"\n## 1. F1 individual runs vs the porous thresholds (a >= 0.85 and beta >= 0.80)")
p(f"F1 runs {ok.height}; individually meeting both thresholds: {int(ok['porous_run'].sum())}")
for r in rules:
    g = ok.filter(pl.col("rule") == r)
    p(f"  {r}: {int(g['porous_run'].sum())}/{g.height}  early a range [{g['early_a'].min():.3f}, {g['early_a'].max():.3f}]")
p("Registered classification is of condition means (6/6 porous); it is not a claim about each run.")

p("\n## 2. Mean early-a shift at 10% noise vs the noise-free ant (6 rules)")
conds = pl.read_csv(RES / "conditions.csv")
C = {r["group"]: r for r in conds.iter_rows(named=True)}
for label, ev, ef in (("revisit-only (0.1, 0)", "0.1", "0"), ("fresh-only (0, 0.1)", "0", "0.1")):
    d = np.array([C[f"hy:{r}:{ev}:{ef}"]["early_a"] - C[f"hy:{r}:0:0"]["early_a"] for r in rules])
    cls = [C[f"hy:{r}:{ev}:{ef}"]["class"] for r in rules]
    p(f"{label}: mean shift {d.mean():+.3f} (between-rule sd {d.std(ddof=1):.3f}, range [{d.min():+.3f}, {d.max():+.3f}]); "
      f"conditions classed compact {cls.count('compact')}/6")

p("\n## 3. Stage 2: window sensitivity of a (CSV k; k = log2 of the window end t)")
df = pl.read_csv(RES / "stage2_probe.csv")


def fit(g, lo, hi):
    w = g.filter((pl.col("k") >= lo) & (pl.col("k") <= hi))
    return np.polyfit(np.log(w["t"].to_numpy().astype(float)), np.log(w["area"].to_numpy().astype(float)), 1)[0]


rng = np.random.default_rng(20261026)
for name, pre in (("rotor", "rotor:"), ("V1", "hy:")):
    specs = [s for s in df["rule"].unique(maintain_order=True) if s.startswith(pre)]
    out = {}
    for lo, hi in ((24, 30), (27, 31)):
        a = np.array([fit(df.filter(pl.col("rule") == s), lo, hi) for s in specs])
        boot = np.array([rng.choice(a, len(a)).mean() for _ in range(10_000)])
        out[(lo, hi)] = a
        p(f"{name} a(k={lo}..{hi}): mean {a.mean():.4f}, sd {a.std(ddof=1):.4f}, n {len(a)}, "
          f"bootstrap 95% of the mean [{np.percentile(boot, 2.5):.4f}, {np.percentile(boot, 97.5):.4f}]")
    d = out[(27, 31)] - out[(24, 30)]
    p(f"{name} per-seed shift a(27..31) - a(24..30): mean {d.mean():+.4f}, sd {d.std(ddof=1):.4f}")
p("A trend interval containing zero is a failure to resolve a trend, not evidence of a plateau; a "
  "significantly negative trend would not by itself identify 2/3 as the limit. Reading: unresolved.")
(RES / "posthoc_review.txt").write_text("\n".join(L) + "\n")
print("\n".join(L))
